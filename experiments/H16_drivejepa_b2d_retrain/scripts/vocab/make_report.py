"""Step 4 of the Bench2Drive path vocabularies: REPORT.md, every number read from the result files in this folder. Numbers only.

Writes (refuses to overwrite): REPORT.md."""
import argparse
import csv
import json
import math
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
SIZES = (256, 512, 1024, 2048, 4096, 8192)
NAVSIM = "{workspace_root}/wa-jepa/Drive-JEPA-upstream/navsim_v2/data/8192.npy"
NAVSIM_SHA = "cc44a31e75a53406db59f026f0358de97931e726f10254542f98d2a87a38ad35"
VOCABS = [f"b2d_{k}" for k in SIZES] + ["navsim_8192"]


def rows(name):
    return list(csv.DictReader(open(f"{HERE}/{name}")))


def table(head, body):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in body])


def label(v):
    return "NAVSIM 8,192" if v == "navsim_8192" else f"{int(v.split('_')[1]):,}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=HERE)
    a = ap.parse_args()
    target = f"{a.out}/REPORT.md"
    if os.path.exists(target):
        sys.exit(f"STOP: {target} exists, not overwriting")

    ex = json.load(open(f"{HERE}/extract_stats.json"))
    km = {k: json.load(open(f"{HERE}/kmeans_{k}.json")) for k in SIZES}
    hand = json.load(open(f"{HERE}/check_handedness.json"))
    load = json.load(open(f"{HERE}/check_load.json"))
    cov = {(r["vocab"], r["split"]): r for r in rows("coverage.csv")}
    grp = rows("groups.csv")
    spd = rows("speed.csv")
    sha = [ln.split() for ln in open(f"{HERE}/SHA256SUMS")]

    z = np.load(f"{HERE}/paths_cache.npz")
    rear, split, clip_id, frame, cmd = (z[k] for k in "rear split clip_id frame cmd".split())
    names, commands = z["clip_names"], list(z["commands"])
    p8 = rear[:, 4::5, :2]
    n_tr, n_he = int((split == 0).sum()), int((split == 1).sum())
    length = np.linalg.norm(np.diff(np.concatenate([np.zeros((len(p8), 1, 2)), p8], 1), axis=1), axis=-1).sum(1)
    move = {}
    for sid, sn in ((0, "train"), (1, "heldout")):
        m = split == sid
        move[sn] = dict(n=int(m.sum()), zero=int((np.abs(p8[m]).max((1, 2)) == 0).sum()), u01=int((length[m] < 0.1).sum()),
                        u1=int((length[m] < 1).sum()), distinct=len(np.unique(np.round(p8[m].reshape(m.sum(), 16), 6), axis=0)))
    near = {v: np.load(f"{HERE}/nearest_{v}.npz") for v in VOCABS}
    vocab = {v: np.load(NAVSIM if v == "navsim_8192" else f"{HERE}/{v}.npy") for v in VOCABS}
    own = {k: int((near[f"b2d_{k}"]["ade"][split == 0] < 1e-5).sum()) for k in SIZES}

    # the fastest training path and the worst held-out path, per size
    tr_idx = np.flatnonzero(split == 0)
    steps = np.linalg.norm(np.diff(np.concatenate([np.zeros((len(p8), 1, 2)), p8], 1), axis=1), axis=-1) / 0.5
    fast = tr_idx[np.argmax(steps[tr_idx].max(1))]
    fast_pos = int(np.flatnonzero(tr_idx == fast)[0])
    fast_grp = {k: int(np.bincount(np.load(f"{HERE}/groups_b2d_{k}.npy"))[np.load(f"{HERE}/groups_b2d_{k}.npy")[fast_pos]]) for k in SIZES}
    he_idx = np.flatnonzero(split == 1)
    worst = he_idx[np.argmax(near["b2d_8192"]["ade"][he_idx])]
    same_centre = {k: float(np.abs(vocab[f"b2d_{k}"][near[f"b2d_{k}"]["idx"][worst], 4::5, :2]
                                   - vocab["b2d_8192"][near["b2d_8192"]["idx"][worst], 4::5, :2]).max()) for k in (2048, 4096)}
    nav_w = tr_idx[np.argmax(near["navsim_8192"]["ade"][tr_idx])]

    # frames whose nearest path ends on the other side
    other = []
    n_sc = {sn: len({r['scenario'] for r in rows('coverage_per_scenario.csv') if r['split'] == sn}) for sn in ('train', 'heldout')}

    def ratio(v, i):
        r = np.linalg.norm(vocab[v][:, :, :2], axis=-1)
        m = (r[:, 4] > 1) & (r[:, 39] > 8)
        return float(np.median(r[m, i] / r[m, 4]))

    for side, sign in (("LEFT", 1.0), ("RIGHT", -1.0)):
        t = (cmd == commands.index(side)) & (np.abs(rear[:, -1, 2]) > math.radians(30))
        for v in VOCABS:
            vy = vocab[v][near[v]["idx"][t], -1, 1]
            bad = sign * vy <= 0
            if bad.any():
                other.append((side, label(v), int(bad.sum()), f"{int(t.sum()):,}", f"{np.abs(rear[t, -1, 1][bad]).max():.2f}", f"{np.abs(vy[bad]).max():.2f}"))

    L = []
    w = L.append
    w("# Bench2Drive path vocabularies: report\n")
    w("05 Nov 2026. Spec: `CLAUDE.md` in this folder. Numbers only. Generated by `make_report.py` from the result files in this folder.\n")

    w("## One row per size\n")
    w("**Groups.** Paths per k-means group, on the training paths.\n")
    w(table(["Size", "Min", "Median", "Max", "Groups with a single path", "Length of the largest group's centre (m)",
             "Largest group: share of paths under 0.1 m"],
            [[f"{int(g['K']):,}", g["min"], f"{float(g['median']):g}", f"{int(g['max']):,}", f"{int(g['single_path_groups']):,}",
              f"{float(g['largest_group_centre_length_m']):.3f}", f"{float(g['largest_group_share_under_0p1m']):.3f}"] for g in grp]))
    w("\n**Coverage.** For each expert path, the distance to its nearest vocabulary path: ADE over the 8 points, in m, searched exactly over "
      "every vocabulary path, on the saved float32 files.\n")
    head = ["Vocabulary", "Train mean", "Train median", "Train p95", "Train max", "Held-out mean", "Held-out median", "Held-out p95", "Held-out max"]
    body = []
    for v in VOCABS:
        t, h = cov[(v, "train")], cov[(v, "heldout")]
        body.append([label(v)] + [f"{float(t[c]):.3f}" for c in ("mean", "median", "p95", "max")]
                    + [f"{float(h[c]):.3f}" for c in ("mean", "median", "p95", "max")])
    w(table(head, body))
    w(f"\nTraining paths: {n_tr:,}. Held-out paths: {n_he:,}. Per scenario type: `coverage_per_scenario.csv` ({n_sc['train']} types in training, {n_sc['heldout']} in held-out; "
      "columns scenario, split, vocab, K, n_paths, n_clips, mean, median, p95, max).\n")
    w("**Speed**, in m/s. One definition for every row: the 8 steps from (0, 0) at t through the 8 points, each step's distance / 0.5 s. "
      "Path mean speed = mean of the 8 steps. Path peak speed = largest of the 8 steps (peak over 0.5 s steps). "
      "A vocabulary's top = the largest over its paths.\n")
    sv = {r["row"]: r for r in spd if r["kind"] == "vocabulary_top"}
    e = {(r["row"], r["kind"]): r for r in spd if r["kind"] != "vocabulary_top"}
    w(table(["Row", "Top mean speed", "Top peak speed"], [[label(v), f"{float(sv[v]['mean_speed']):.2f}", f"{float(sv[v]['peak_speed']):.2f}"] for v in VOCABS]))
    w("")
    w(table(["Expert", "Mean speed p99", "Mean speed max", "Peak speed p99", "Peak speed max"],
            [[sn, f"{float(e[(f'expert_{s}', 'p99')]['mean_speed']):.2f}", f"{float(e[(f'expert_{s}', 'max')]['mean_speed']):.2f}",
              f"{float(e[(f'expert_{s}', 'p99')]['peak_speed']):.2f}", f"{float(e[(f'expert_{s}', 'max')]['peak_speed']):.2f}"]
             for s, sn in (("train", "Training paths"), ("heldout", "Held-out paths"))]))
    w(f"\nThe fastest training path is `{names[clip_id[fast]]}` frame {frame[fast]}. Paths in its group, by size: "
      + ", ".join(f"{k:,}: {fast_grp[k]}" for k in SIZES) + ".\n")

    w("## Read with these numbers\n")
    w(f"- **Paths against sizes.** {n_tr:,} training paths, {move['train']['distinct']:,} of them distinct (16 numbers, rounded to 1e-6 m). That is "
      f"{n_tr / 8192:.1f} paths per group on average at 8,192.")
    w("- **The training rows of coverage are in-sample.** Training paths that are themselves a vocabulary path (ADE under 1e-5 m): "
      + ", ".join(f"{k:,}: {own[k]:,}" for k in SIZES) + ". The held-out paths were not used to build any vocabulary.")
    w(f"- **Stationary paths.** Training: {move['train']['zero']:,} exactly zero, {move['train']['u01']:,} ({move['train']['u01'] / n_tr:.1%}) under 0.1 m long, "
      f"{move['train']['u1']:,} ({move['train']['u1'] / n_tr:.1%}) under 1 m. Held-out: {move['heldout']['zero']:,} exactly zero, {move['heldout']['u01']:,} "
      f"({move['heldout']['u01'] / n_he:.1%}) under 0.1 m, {move['heldout']['u1']:,} ({move['heldout']['u1'] / n_he:.1%}) under 1 m. "
      "So the train and held-out rows average over different shares of stationary paths. All paths are weighted the same. The largest group at every size is the stationary one (groups table).")
    w(f"- **Held-out max.** The held-out max at 8,192 is `{names[clip_id[worst]]}` frame {frame[worst]}, ADE {float(near['b2d_8192']['ade'][worst]):.3f} m. "
      f"Its nearest path at 2,048 and 4,096 has the same 8 points (largest gap {max(same_centre.values()):.1e} m), so the three rows show the same value.")
    w(f"- **NAVSIM's largest distance** on the training paths is `{names[clip_id[nav_w]]}` frame {frame[nav_w]}, ADE {float(near['navsim_8192']['ade'][nav_w]):.2f} m "
      f"(expert ends at x {rear[nav_w, -1, 0]:.1f}, y {rear[nav_w, -1, 1]:.1f} m, heading {math.degrees(rear[nav_w, -1, 2]):.1f} degrees).")
    w("- **Groups and coverage use different distances.** k-means groups by squared distance over the 16 numbers; coverage uses ADE. A path's nearest vocabulary path need not be its group's centre.\n")

    w("## Paths and frames\n")
    w(table(["", "Clips", "2 Hz frames", "Used", "Skipped (under 4 s of future)"],
            [["Train", ex["clips"]["train"], f"{ex['frames_total']['train']:,}", f"{ex['frames_used']['train']:,}", f"{ex['frames_skipped']['train']:,}"],
             ["Held-out", ex["clips"]["heldout"], f"{ex['frames_total']['heldout']:,}", f"{ex['frames_used']['heldout']:,}", f"{ex['frames_skipped']['heldout']:,}"]]))
    w(f"\nThe skipped frames are the last 8 samples of each clip: {ex['frames_skipped']['train'] + ex['frames_skipped']['heldout']:,} = 944 x 8. "
      f"Holes inside a future: {len(ex['holes_inside_future'])}. Not-finite values where valid: {ex['nan_where_valid']}. Sample steps other than 5 frames: {ex['sample_steps_not_5_frames']}. "
      f"Clips with no path: {len(ex['clips_with_no_path'])}. All 944 label files carry schema `phase0a-b2d-v4`.\n")
    w("Source: `{data.b2d_clips}/labels_b2d_v4/b2d`, one `ego.future` and `ego.future_valid` per sample. Not phase1-targets-v2. "
      "`splits/clips.json` verified: 944 clips = 897 train + 47 held-out with no overlap, the text lists match, all 944 label files exist, none of the 24 removed twins are in `clips`, no route id is in both splits. "
      "Frame list: `frames_used.csv` (clip, frame, split). Only clips in `clips.json` were read: their label files, and the raw anno and front-camera frames of the 4 examples in check 2.\n")

    w("## Format found\n")
    w(f"Drive-JEPA's `navsim_v2/data/8192.npy`: sha256 `{NAVSIM_SHA}` (matches the value given). Shape (8192, 40, 3), float32, C order, npy 1.0.\n")
    w("- **The Format row of the spec says 8 poses. The file has 40 poses, 0.1 s apart.** The agent takes `poses[:, 4::5]` to get NAVSIM's 8 poses at 0.5 s "
      "(`drive_jepa_agent.py:49-50`, `calc_anchors_scores.py:15-16`). A file of 8 poses would give 1 pose after that slice, so these files are (K, 40, 3), as instructed.")
    w(f"- **Pose index 0 is t + 0.1 s, not t.** Index 39 is t + 4.0 s, in Drive-JEPA's file and here: median |pose 0| / |pose 4| is {ratio('navsim_8192', 0):.3f} in Drive-JEPA's file and {ratio('b2d_8192', 0):.3f} in `b2d_8192.npy`; median |pose 39| / |pose 4| is {ratio('navsim_8192', 39):.2f} and {ratio('b2d_8192', 39):.2f} (paths with |pose 4| above 1 m and |pose 39| above 8 m).")
    w(f"- **Labels are 10 Hz.** Least-squares of distance against the anno speed over {hand['timing']['frames']:,} frames above 2 m/s: index 0 = {hand['timing']['seconds_at_index_0']:.3f} s, index 4 = {hand['timing']['seconds_at_index_4']:.3f} s.")
    w(f"- File size: `b2d_8192.npy` {os.path.getsize(HERE + '/b2d_8192.npy'):,} bytes, `8192.npy` {os.path.getsize(NAVSIM):,} bytes.\n")
    body = []
    for v in VOCABS:
        q = vocab[v]
        body.append([label(v), str(q.shape), f"{q[:, -1, 0].min():.1f} to {q[:, -1, 0].max():.1f}", f"{q[:, -1, 1].min():.1f} to {q[:, -1, 1].max():.1f}",
                     f"{q[..., 2].min():.2f} to {q[..., 2].max():.2f}"])
    w(table(["Vocabulary", "Shape", "x at 4 s (m)", "y at 4 s (m)", "Heading, all poses (rad)"], body))

    w("\n## What was applied\n")
    w(table(["Step", "Applied", "Where"],
            [["CARLA flip (y and yaw)", "Once, by Phase 0a, when the labels were built. Not applied here", "`labels_b2d.ego_pose`, `Frame.to_local`"],
             ["Rear-axle shift", f"Once, here, on all 40 poses of every path: {ex['rear_axle_offset_m']} m", "imported `phase1.data.targets.rear_axle_poses`, constant `geometry.B2D_REAR_AXLE_OFFSET`"],
             ["10 Hz to 2 Hz", "Not applied to the poses: all 40 stay in the file. `[4::5]` gives the 8 points", "`extract_paths.py`, `build_vocab.py`"]]))
    rt = hand["rear_axle_test_rad"]
    w(f"\nRear-axle test: a rear axle moves along its heading, so on {rt['frames']:,} turning frames (end heading beyond 0.8 rad, above 2 m/s) mean |path tangent - heading| in rad is:\n")
    w(table(["Actor origin (no shift)", "Rear axle (shift once, as saved)", "Shift twice", "Shift in the wrong direction"],
            [[f"{rt['actor_origin']:.4f}", f"{rt['rear_axle_once']:.4f}", f"{rt['rear_axle_twice']:.4f}", f"{rt['wrong_direction']:.4f}"]]))

    w("\n## Clustering: every value used\n")
    s = km[256]["settings"]
    w(table(["Setting", "Value"],
            [["Library", f"scikit-learn {km[256]['sklearn']} `KMeans`, in `{drivejepa_env}/.venv` (Python 3.9.25, numpy 1.24.0). Nothing installed"],
             ["Input", f"{km[256]['n_paths']:,} training paths; 8 (x, y) points at 0.5 .. 4.0 s, flattened to 16 numbers; metres, no scaling; every path weight 1; float64"],
             ["Start", f"`init={s['init']}`, `n_init={s['n_init']}`"], ["Algorithm", f"`{s['algorithm']}`"],
             ["Stop", f"`tol={s['tol']}` (stops only when no label changes), `max_iter={s['max_iter']}`"], ["Seed", f"`random_state={s['random_state']}`, the same at every size"],
             ["Centre", "Mean of its members at each of the 40 steps; heading the circular mean (atan2 of mean sin, mean cos). Cast to float32 last"],
             ["Threads", "8 (OMP_NUM_THREADS, OPENBLAS_NUM_THREADS)"]]))
    w("")
    w(table(["Size", "Iterations", "Converged", "Labels unchanged on final centres", "Inertia (m^2)", "Largest gap, member mean to k-means centre (m)",
             "Largest gap, saved float32 to centre (m)", "Smallest heading resultant length", "Fit (s)"],
            [[f"{k:,}", km[k]["n_iter"], "yes" if km[k]["converged"] else "no", f"{km[k]['labels_unchanged_on_final_centres']:.4f}", f"{km[k]['inertia']:,.1f}",
              f"{km[k]['max_gap_member_mean_vs_kmeans_centre_m']:.1e}", f"{km[k]['max_gap_saved_float32_vs_kmeans_centre_m']:.1e}",
              f"{km[k]['min_heading_resultant_length']:.3f}", km[k]["fit_seconds"]] for k in SIZES]))
    w("\nNo group is empty at any size. Repeat runs on the same 8 threads gave the same sha256 at 256 and at 8,192; sklearn's threaded sums can differ in the last digits (inertia did at 256), so other thread counts may not reproduce the bytes.\n")
    w(f"Limits kept: `nice -n 15 ionice -c3`, `CUDA_VISIBLE_DEVICES=\"\"`, at most 8 threads. Peak memory {max(km[k]['peak_rss_gb'] for k in SIZES):.2f} GB (k-means), {ex['peak_rss_gb']:.2f} GB (extraction).\n")

    w("## Check 1: loads\n")
    w("`check_load.py` runs the real `DriveJEPAAgent.__init__` from Drive-JEPA-upstream with only the network stubbed (no weights), in a temporary working directory where `data/8192.npy` is a symlink to the file under test. "
      "Then navsim's `Trajectory` on every path of `self.anchors`, and the real `trajectory_loss_anchors` with random proposals and random indices. Drive-JEPA's own file first, as the reference. Drive-JEPA was not edited.\n")
    w(table(["File", "File shape", "self.anchors", "dtype", "Trajectory accepted", "Loss finite"],
            [[r["vocab"], tuple(r["file_shape"]), tuple(r["anchors_shape"]), r["anchors_dtype"], f"{r['trajectory_ok']:,}", "yes" if r["loss_finite"] else "no"] for r in load["rows"]]))

    w("\n### Places in Drive-JEPA that assume the 8,192 file\n")
    w("Searched `navsim_v2/navsim/agents/drive_jepa_perception_based`, `navsim_v2/scripts` and the configs under `navsim_v2/navsim/planning/script/config`. "
      "**The count 8,192 is written nowhere as a number; it appears only in the file name, twice.** No config or yaml sets the vocabulary path or size (the other hits for 8192 are hex scene tokens in the scene filters).\n")
    w(table(["Place", "What it assumes", "Hard-coded"],
            [["`navsim/agents/drive_jepa_perception_based/drive_jepa_agent.py:49`", "`np.load(\"./data/8192.npy\")`: file name, relative to the working directory, no config option", "File name"],
             ["`drive_jepa_agent.py:50`", "`poses[:, 4::5]`: 40 poses per path", "Pose layout, not the count"],
             ["`scripts/misc/calc_anchors_scores.py:15-16`", "The same load and slice", "File name"],
             ["`anchors_scores_index_v2` cache, read at `score_module/compute_navsim_score.py:54-55`, used at `drive_jepa_agent.py:246` (`self.anchors[sampled_idx]`)",
              "Holds indices into one vocabulary. Indices from the 8,192 file raise IndexError on a smaller file whenever one is K or above, and on `b2d_8192.npy` they stay in range and silently pick unrelated paths. Any new vocabulary needs its own index cache", "Tied to the file by data, not by a constant"],
             ["`scripts/misc/convert_to_index.py:21-22`", "Caps an index list at 256 (and keeps scores >= 0.95, line 18). A count constant, but not 8,192. At size 256 the cap cannot trigger", "256"]]))
    w("\nNot tied to the vocabulary size: `proposal_num` = 32 (`drive_jepa_config.py:27`), `num_poses` = 8 (line 36), `num_pseudo_targets` = 4 (line 49), `TrajectorySampling(num_poses=40, interval_length=0.1)` (`drive_jepa_model.py:22`).\n")
    w("Found alongside, relevant if the scores are rebuilt:\n")
    w("- `calc_anchors_scores.py:8` and `convert_to_index.py:8` import `navsim.agents.pad_vjepa.score_module_v2`, which is not in this tree (`find_spec` returns None), so both fail as written.")
    w("- `calc_anchors_scores.py:18` unpacks 4 values; this tree's `get_sub_score` returns 5 (`compute_navsim_score.py:76`).")
    w("- This tree's `get_sub_score` also reads an `anchors_scores_index_v2` file (line 55). `calc_anchors_scores.py` calls it before `convert_to_index.py` has written any index.")
    w("- `get_sub_score` scores against a NAVSIM metric cache. No anchor scores were computed here.\n")

    w("## Check 2: handedness\n")
    w("Frames: turn scenarios with `command_near` LEFT or RIGHT, above 2 m/s, the largest end heading in the split. The raw columns come from the clip's anno files, which do not pass through Phase 0a's flip: in CARLA (left-handed, y right), a left turn has a negative yaw change and a negative offset along the right vector.\n")
    w(table(["Command", "Split", "Clip", "Frame", "Expert x, y at 4 s (m)", "Expert heading at 4 s (deg)", "Raw CARLA yaw change (deg)", "Raw CARLA offset to the right (m)"],
            [[q["command"], q["split"], f"`{q['clip']}`", q["frame"], f"{q['expert']['x_end']:.2f}, {q['expert']['y_end']:.2f}", f"{q['expert']['yaw_end_deg']:.2f}",
              f"{q['raw_carla']['carla_yaw_change_deg']:.2f}", f"{q['raw_carla']['carla_offset_right_m']:.2f}"] for q in hand["examples"]]))
    w("\nExpert y (m) at the 8 points:\n")
    w(table(["Example"] + [f"{0.5 * i:.1f} s" for i in range(1, 9)], [[f"{q['command']} {q['split']}"] + q["expert"]["y_at_8_points"] for q in hand["examples"]]))
    w("\nNearest vocabulary path to each example: y at 4 s (m) / heading at 4 s (deg) / ADE (m). The training examples are in-sample, so ADE 0.000 means the path is its own group.\n")
    w(table(["Vocabulary"] + [f"{q['command']} {q['split']}" for q in hand["examples"]],
            [[label(v)] + [f"{q['nearest'][v]['y_end']:.2f} / {q['nearest'][v]['yaw_end_deg']:.1f} / {q['nearest'][v]['ade']:.3f}" for q in hand["examples"]] for v in VOCABS]))
    w("\nEvery frame with that `command_near` and an end heading beyond 30 degrees (Phase 0a's turn cut): share whose end y is on the command's side.\n")
    w(table(["Command", "Split", "Frames with command", "Beyond 30 deg", "Expert"] + [label(v) for v in VOCABS],
            [[r["command"], r["split"], f"{r['frames_with_command']:,}", f"{r['end_heading_beyond_30deg']:,}", f"{r['expert_share_y_toward_side']:.3f}"]
             + [f"{r['nearest_share_y_toward_side'][v]:.3f}" for v in VOCABS] for r in hand["all_turn_frames"]]))
    w("\nFrames (train and held-out together) whose nearest path ends on the other side:\n")
    w(table(["Command", "Vocabulary", "Frames", "Of", "Largest expert abs(y) at 4 s in these (m)", "Largest nearest abs(y) at 4 s in these (m)"], other))
